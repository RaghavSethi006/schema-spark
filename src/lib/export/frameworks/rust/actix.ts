function generateMainRs(schema: ERSchema, config: ExportConfig): string {
  const handlerImports = schema.entities.map(e => 
    `use crate::handlers::${toSnakeCase(e.name)}::*;`
  ).join('\n');
  
  const routes = schema.entities.map(e => {
    const name = toSnakeCase(e.name);
    return `            .service(
                web::scope("/${name}s")
                    .route("", web::get().to(get_all_${name}s))
                    .route("", web::post().to(create_${name}))
                    .route("/{id}", web::get().to(get_${name}))
                    .route("/{id}", web::put().to(update_${name}))
                    .route("/{id}", web::delete().to(delete_${name}))
            )`;
  }).join('\n');

  return `use actix_cors::Cors;
use actix_web::{web, App, HttpServer, middleware};
use sqlx::postgres::PgPoolOptions;
use tracing_subscriber::{layer::SubscriberExt, util::SubscriberInitExt};

mod config;
mod db;
mod error;
mod handlers;
mod models;
mod services;

${handlerImports}

#[actix_web::main]
async fn main() -> std::io::Result<()> {
    // Initialize logging
    tracing_subscriber::registry()
        .with(tracing_subscriber::EnvFilter::new(
            std::env::var("RUST_LOG").unwrap_or_else(|_| "info".into()),
        ))
        .with(tracing_subscriber::fmt::layer())
        .init();

    // Load configuration
    dotenv::dotenv().ok();
    let database_url = std::env::var("DATABASE_URL")
        .expect("DATABASE_URL must be set");
    
    // Create database pool
    let pool = PgPoolOptions::new()
        .max_connections(5)
        .connect(&database_url)
        .await
        .expect("Failed to create pool");

    tracing::info!("Starting server at http://localhost:8080");

    HttpServer::new(move || {
        let cors = Cors::default()
            .allow_any_origin()
            .allow_any_method()
            .allow_any_header();

        App::new()
            .app_data(web::Data::new(pool.clone()))
            .wrap(cors)
            .wrap(middleware::Logger::default())
${routes}
    })
    .bind(("127.0.0.1", 8080))?
    .run()
    .await
}
`;
}

