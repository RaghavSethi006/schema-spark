function generateRustModel(entity: any, config: ExportConfig): string {
  const name = toPascalCase(entity.name);
  const fields = entity.fields.map((f: any) => {
    const rustType = mapToRustType(f.type, f.isNullable);
    return `    pub ${toSnakeCase(f.name)}: ${rustType},`;
  }).join('\n');
  
  const createFields = entity.fields
    .filter((f: any) => !f.isPrimaryKey)
    .map((f: any) => {
      const rustType = mapToRustType(f.type, f.isNullable);
      return `    pub ${toSnakeCase(f.name)}: ${rustType},`;
    }).join('\n');

  return `use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use sqlx::FromRow;
use uuid::Uuid;
use validator::Validate;

/// ${name} entity
#[derive(Debug, Clone, Serialize, Deserialize, FromRow)]
pub struct ${name} {
${fields}
}

/// DTO for creating a new ${name}
#[derive(Debug, Clone, Serialize, Deserialize, Validate)]
pub struct Create${name} {
${createFields}
}

/// DTO for updating an existing ${name}
#[derive(Debug, Clone, Serialize, Deserialize, Validate)]
pub struct Update${name} {
${entity.fields.filter((f: any) => !f.isPrimaryKey).map((f: any) => {
  const rustType = mapToRustType(f.type, true); // All optional for updates
  return `    pub ${toSnakeCase(f.name)}: ${rustType},`;
}).join('\n')}
}

impl ${name} {
    /// Create a new ${name} from a Create DTO
    pub fn from_create(dto: Create${name}) -> Self {
        Self {
            id: Uuid::new_v4(),
${entity.fields.filter((f: any) => !f.isPrimaryKey).map((f: any) => {
  return `            ${toSnakeCase(f.name)}: dto.${toSnakeCase(f.name)},`;
}).join('\n')}
        }
    }
}
`;
}

function generateRustHandler(entity: any, config: ExportConfig): string {
  const name = toPascalCase(entity.name);
  const snakeName = toSnakeCase(entity.name);
  
  return `use actix_web::{web, HttpResponse, Result};
use sqlx::PgPool;
use uuid::Uuid;

use crate::error::AppError;
use crate::models::${snakeName}::{${name}, Create${name}, Update${name}};
use crate::services::${snakeName}::${name}Service;

/// Get all ${name}s
pub async fn get_all_${snakeName}s(
    pool: web::Data<PgPool>,
) -> Result<HttpResponse, AppError> {
    let items = ${name}Service::find_all(pool.get_ref()).await?;
    Ok(HttpResponse::Ok().json(items))
}

/// Get a single ${name} by ID
pub async fn get_${snakeName}(
    pool: web::Data<PgPool>,
    path: web::Path<Uuid>,
) -> Result<HttpResponse, AppError> {
    let id = path.into_inner();
    let item = ${name}Service::find_by_id(pool.get_ref(), id).await?;
    
    match item {
        Some(item) => Ok(HttpResponse::Ok().json(item)),
        None => Ok(HttpResponse::NotFound().finish()),
    }
}

/// Create a new ${name}
pub async fn create_${snakeName}(
    pool: web::Data<PgPool>,
    body: web::Json<Create${name}>,
) -> Result<HttpResponse, AppError> {
    let item = ${name}Service::create(pool.get_ref(), body.into_inner()).await?;
    Ok(HttpResponse::Created().json(item))
}

/// Update an existing ${name}
pub async fn update_${snakeName}(
    pool: web::Data<PgPool>,
    path: web::Path<Uuid>,
    body: web::Json<Update${name}>,
) -> Result<HttpResponse, AppError> {
    let id = path.into_inner();
    let item = ${name}Service::update(pool.get_ref(), id, body.into_inner()).await?;
    
    match item {
        Some(item) => Ok(HttpResponse::Ok().json(item)),
        None => Ok(HttpResponse::NotFound().finish()),
    }
}

/// Delete a ${name}
pub async fn delete_${snakeName}(
    pool: web::Data<PgPool>,
    path: web::Path<Uuid>,
) -> Result<HttpResponse, AppError> {
    let id = path.into_inner();
    let deleted = ${name}Service::delete(pool.get_ref(), id).await?;
    
    if deleted {
        Ok(HttpResponse::NoContent().finish())
    } else {
        Ok(HttpResponse::NotFound().finish())
    }
}
`;
}

function generateRustService(entity: any, config: ExportConfig): string {
  const name = toPascalCase(entity.name);
  const snakeName = toSnakeCase(entity.name);
  const tableName = config.tablePluralizer ? `${snakeName}s` : snakeName;
  
  return `use sqlx::PgPool;
use uuid::Uuid;

use crate::error::AppError;
use crate::models::${snakeName}::{${name}, Create${name}, Update${name}};

pub struct ${name}Service;

impl ${name}Service {
    /// Find all ${name}s
    pub async fn find_all(pool: &PgPool) -> Result<Vec<${name}>, AppError> {
        let items = sqlx::query_as::<_, ${name}>(
            "SELECT * FROM ${tableName}"
        )
        .fetch_all(pool)
        .await?;
        
        Ok(items)
    }

    /// Find a ${name} by ID
    pub async fn find_by_id(pool: &PgPool, id: Uuid) -> Result<Option<${name}>, AppError> {
        let item = sqlx::query_as::<_, ${name}>(
            "SELECT * FROM ${tableName} WHERE id = $1"
        )
        .bind(id)
        .fetch_optional(pool)
        .await?;
        
        Ok(item)
    }

    /// Create a new ${name}
    pub async fn create(pool: &PgPool, input: Create${name}) -> Result<${name}, AppError> {
        let entity = ${name}::from_create(input);
        
        sqlx::query(
            "INSERT INTO ${tableName} (id${entity.fields.filter((f: any) => !f.isPrimaryKey).map((f: any) => `, ${toSnakeCase(f.name)}`).join('')}) VALUES ($1${entity.fields.filter((f: any) => !f.isPrimaryKey).map((_: any, i: number) => `, $${i + 2}`).join('')})"
        )
        .bind(&entity.id)
${entity.fields.filter((f: any) => !f.isPrimaryKey).map((f: any) => `        .bind(&entity.${toSnakeCase(f.name)})`).join('\n')}
        .execute(pool)
        .await?;
        
        Ok(entity)
    }

    /// Update an existing ${name}
    pub async fn update(pool: &PgPool, id: Uuid, input: Update${name}) -> Result<Option<${name}>, AppError> {
        // Build dynamic update query based on provided fields
        let result = sqlx::query(
            "UPDATE ${tableName} SET updated_at = NOW() WHERE id = $1"
        )
        .bind(id)
        .execute(pool)
        .await?;
        
        if result.rows_affected() == 0 {
            return Ok(None);
        }
        
        Self::find_by_id(pool, id).await
    }

    /// Delete a ${name}
    pub async fn delete(pool: &PgPool, id: Uuid) -> Result<bool, AppError> {
        let result = sqlx::query("DELETE FROM ${tableName} WHERE id = $1")
            .bind(id)
            .execute(pool)
            .await?;
        
        Ok(result.rows_affected() > 0)
    }
}
`;
}

function generateErrorModule(): string {
  return `use actix_web::{HttpResponse, ResponseError};
use std::fmt;

#[derive(Debug)]
pub enum AppError {
    Database(sqlx::Error),
    Validation(String),
    NotFound(String),
    Conflict(String),
    Internal(String),
}

impl fmt::Display for AppError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            AppError::Database(e) => write!(f, "Database error: {}", e),
            AppError::Validation(msg) => write!(f, "Validation error: {}", msg),
            AppError::NotFound(msg) => write!(f, "Not found: {}", msg),
            AppError::Conflict(msg) => write!(f, "Conflict: {}", msg),
            AppError::Internal(msg) => write!(f, "Internal error: {}", msg),
        }
    }
}

impl std::error::Error for AppError {}

impl ResponseError for AppError {
    fn error_response(&self) -> HttpResponse {
        match self {
            AppError::Database(_) => HttpResponse::InternalServerError().json(serde_json::json!({
                "error": "Database error"
            })),
            AppError::Validation(msg) => HttpResponse::BadRequest().json(serde_json::json!({
                "error": msg
            })),
            AppError::NotFound(msg) => HttpResponse::NotFound().json(serde_json::json!({
                "error": msg
            })),
            AppError::Conflict(msg) => HttpResponse::Conflict().json(serde_json::json!({
                "error": msg
            })),
            AppError::Internal(msg) => HttpResponse::InternalServerError().json(serde_json::json!({
                "error": msg
            })),
        }
    }
}

impl From<sqlx::Error> for AppError {
    fn from(err: sqlx::Error) -> Self {
        AppError::Database(err)
    }
}
`;
}

