// Actix Web Framework Adapter (Rust)
import { FrameworkAdapter, FrameworkFeatures, ORMType } from '../../types/frameworks';
import { DatabaseType, AnyDatabaseAdapter } from '../../types/databases';
import { ExportConfig } from '../../types/config';
import { GeneratedFile, toPascalCase, toSnakeCase, CanonicalIR } from '../../types/core';
import { ERSchema } from '../../../schema';

const actixFeatures: FrameworkFeatures = {
  orm: 'SQLx / Diesel / SeaORM',
  migrations: true,
  validation: true,
  authentication: true,
  swagger: true,
  graphql: true,
  testing: true,
  docker: true,
};

export const actixAdapter: FrameworkAdapter = {
  id: 'actix',
  name: 'Actix Web',
  language: 'rust',
  description: 'Powerful, pragmatic, and extremely fast web framework for Rust',
  features: actixFeatures,
  supportedDatabases: ['postgresql', 'mysql', 'sqlite'] as DatabaseType[],
  supportedORMs: ['sqlx', 'diesel', 'sea-orm'] as ORMType[],
  
  generateProject(schema: ERSchema, dbAdapter: AnyDatabaseAdapter, config: ExportConfig): GeneratedFile[] {
    const files: GeneratedFile[] = [];
    const projectName = toSnakeCase(config.projectName);
    const base = projectName;
    
    // Cargo.toml
    files.push({
      path: `${base}/Cargo.toml`,
      content: generateCargoToml(projectName, config),
      type: 'config',
    });
    
    // Main entry point
    files.push({
      path: `${base}/src/main.rs`,
      content: generateMainRs(schema, config),
      type: 'config',
    });
    
    // Database configuration
    files.push({
      path: `${base}/src/db.rs`,
      content: generateDbModule(config),
      type: 'config',
    });
    
    // Models
    schema.entities.forEach(entity => {
      files.push({
        path: `${base}/src/models/${toSnakeCase(entity.name)}.rs`,
        content: generateRustModel(entity, config),
        type: 'model',
      });
    });
    
    // Models mod.rs
    files.push({
      path: `${base}/src/models/mod.rs`,
      content: schema.entities.map(e => `pub mod ${toSnakeCase(e.name)};`).join('\n') + '\n\n' +
        schema.entities.map(e => `pub use ${toSnakeCase(e.name)}::*;`).join('\n'),
      type: 'model',
    });
    
    // Handlers (controllers)
    if (config.generateControllers) {
      schema.entities.forEach(entity => {
        files.push({
          path: `${base}/src/handlers/${toSnakeCase(entity.name)}.rs`,
          content: generateRustHandler(entity, config),
          type: 'controller',
        });
      });
      
      files.push({
        path: `${base}/src/handlers/mod.rs`,
        content: schema.entities.map(e => `pub mod ${toSnakeCase(e.name)};`).join('\n'),
        type: 'controller',
      });
    }
    
    // Services
    if (config.generateServices) {
      schema.entities.forEach(entity => {
        files.push({
          path: `${base}/src/services/${toSnakeCase(entity.name)}.rs`,
          content: generateRustService(entity, config),
          type: 'service',
        });
      });
      
      files.push({
        path: `${base}/src/services/mod.rs`,
        content: schema.entities.map(e => `pub mod ${toSnakeCase(e.name)};`).join('\n'),
        type: 'service',
      });
    }
    
    // Error handling
    files.push({
      path: `${base}/src/error.rs`,
      content: generateErrorModule(),
      type: 'other',
    });
    
    // Configuration
    files.push({
      path: `${base}/src/config.rs`,
      content: generateConfigModule(config),
      type: 'config',
    });
    
    // README
    if (config.generateReadme) {
      files.push({
        path: `${base}/README.md`,
        content: generateActixReadme(projectName, config),
        type: 'readme',
      });
    }
    
    return files;
  },
  
  getModelFileName: (entityName) => `${toSnakeCase(entityName)}.rs`,
  getControllerFileName: (entityName) => `${toSnakeCase(entityName)}.rs`,
  getSchemaFileName: (entityName) => `${toSnakeCase(entityName)}.rs`,
  getServiceFileName: (entityName) => `${toSnakeCase(entityName)}.rs`,
  getMigrationFileName: (entityName, timestamp) => `${timestamp}_create_${toSnakeCase(entityName)}.rs`,
};

